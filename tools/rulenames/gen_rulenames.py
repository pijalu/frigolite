#!/usr/bin/env python3
"""Generate internal/parse/rule_names.go from SQLite's parse.y.

Extracts grammar rules in lemon order, cross-validates each rule's RHS
symbol count against frigolite's yyRuleInfoNRhs table, and emits:
  - ruleNames: descriptive Go identifiers (ruleCmdBeginTranstypeTransOpt)
  - ruleGrammar: "lhs ::= rhs" text per rule (drift documentation)

Usage: python3 gen_rulenames.py <parse.y> <internal/parse/sql_tables.go> > rule_names.go
Regenerate whenever the parse tables are rebuilt from a new grammar.
"""
import re, sys

def parse_y_rules(path):
    """Scan parse.y for grammar rules; each ends at its '.' terminator.

    Action blocks { ... } are skipped with brace counting that RESETS at
    every rule start (actions never span rules), so C code containing
    unbalanced-looking braces inside strings cannot desync the scanner.
    Block comments /* */ are skipped likewise.
    """
    rules = []
    text = open(path).read()
    text = re.sub(r'/\*.*?\*/', ' ', text, flags=re.S)  # block comments
    lines = text.split('\n')
    i = 0
    n = len(lines)
    rule_re = re.compile(r'^([a-zA-Z_][a-zA-Z0-9_]*)(\([^)]*\))?\s*::=\s*(.*)$')
    while i < n:
        line = lines[i].strip()
        if line.startswith('%'):
            # directive: skip its brace block if present, else the line
            depth = line.count('{') - line.count('}')
            i += 1
            while depth > 0 and i < n:
                depth += lines[i].count('{') - lines[i].count('}')
                i += 1
            continue
        if not line or line.startswith('//'):
            i += 1
            continue
        m = rule_re.match(line)
        if not m:
            i += 1
            continue
        lhs = m.group(1)
        rhs = m.group(3).strip()
        depth = rhs.count('{') - rhs.count('}')
        i += 1
        # accumulate continuation lines until the '.' terminator, skipping
        # action blocks
        while i < n:
            line = lines[i].strip()
            if not line.startswith('//'):
                if depth == 0:
                    brace = line.find('{')
                    seg = (line[:brace] if brace >= 0 else line).strip()
                    if seg.endswith('.') or seg == '.':
                        seg = seg.rstrip('.').strip()
                        if seg:
                            rhs = (rhs + ' ' + seg).strip()
                        i += 1
                        break
                    if seg:
                        rhs = (rhs + ' ' + seg).strip()
                    if brace >= 0:
                        depth += line[brace:].count('{') - line[brace:].count('}')
                else:
                    depth += line.count('{') - line.count('}')
            i += 1
        rhs = rhs.replace('.', ' ').strip()
        rules.append((lhs, re.sub(r'\s+', ' ', rhs)))
    return rules

def rhs_count(rhs):
    if not rhs:
        return 0
    toks = [t for t in rhs.split() if t not in ('.',) and not t.startswith('[')]
    # strip a trailing '.' terminator if present
    if toks and toks[-1] == '.':
        toks = toks[:-1]
    return len(toks)

def go_name(lhs, rhs, idx):
    parts = [lhs] + [t for t in rhs.replace('[','').replace(']','').split() if t]
    words = []
    for p in parts:
        for w in re.split(r'[_]+', p):
            if w:
                words.append(w[0].upper() + w[1:])
    name = 'rule' + ''.join(words)
    if len(name) > 80:
        name = name[:77] + 'N%03d' % idx
    return name

def main():
    ypath, tpath = sys.argv[1], sys.argv[2]
    rules = parse_y_rules(ypath)
    tsrc = open(tpath).read()
    def arr(name):
        m = re.search(r'var %s = \[\]int\{(.*?)\}' % name, tsrc, re.S)
        return [x for x in re.sub(r'\s+', ' ', m.group(1)).strip().split(',') if x.strip()]
    lhs_tab = arr('yyRuleInfoLhs')
    nrhs_tab = arr('yyRuleInfoNRhs')
    if len(rules) < len(lhs_tab):
        sys.exit('only %d rules extracted, tables have %d' % (len(rules), len(lhs_tab)))
    # lemon numbers rules in grammar order; frigolite tables may prune leading
    # rules — align by scanning for the first offset where nrhs matches for a
    # window of rules.
    offset = 0
    for off in range(0, len(rules) - len(nrhs_tab) + 1):
        ok = all(rhs_count(rules[off + i][1]) == int(nrhs_tab[i]) for i in range(min(40, len(nrhs_tab))))
        if ok:
            offset = off
            break
    mismatch = [i for i in range(len(nrhs_tab)) if rhs_count(rules[offset + i][1]) != int(nrhs_tab[i])]
    if mismatch:
        sys.exit('nrhs mismatch at table rules: %s' % mismatch[:10])
    seen = {}
    print('// Code generated by tools/rulenames/gen_rulenames.py from SQLite parse.y.')
    print('// Regenerate after rebuilding the parse tables. Descriptive names for the')
    print('// grammar rules dispatched by ruleHandlers (parser_rules*.go).')
    print()
    print('package parse')
    print()
    print('// yyRuleGrammar holds the "lhs ::= rhs" text of each grammar rule, in')
    print('// lemon rule order. Index = the ruleNo passed to ruleHandler.')
    print('var yyRuleGrammar = [%d]string{' % len(nrhs_tab))
    for i in range(len(nrhs_tab)):
        lhs, rhs = rules[offset + i]
        txt = (lhs + ' ::= ' + rhs).replace('\\', '').replace('"', '')
        print('\t%d: %q,' % (i, txt))
    print('}')
    print()
    print('// Descriptive names for the rule handlers. Same indices as yyRuleGrammar.')
    print('var yyRuleDesc = [%d]string{' % len(nrhs_tab))
    for i in range(len(nrhs_tab)):
        lhs, rhs = rules[offset + i]
        nm = go_name(lhs, rhs, i)
        if nm in seen:
            seen[nm] += 1
            nm += 'N%03d' % i
        else:
            seen[nm] = 1
        print('\t%d: %q,' % (i, nm))
    print('}')

if __name__ == '__main__':
    main()
