// check.go — `--check` mode for `tools/status` (PORTPLAN §5g item 1).
//
// `tools/status --check` runs the regular `tools/status` report (live run or
// cached last_run.json) and diffs the resulting per-package states against the
// GREEN-LEDGER (`tools/status/ledger.json`). It exits non-zero on ANY
// unexpected state flip:
//
//   pass    →  fail       (regression in a previously-green package)
//   skipped →  fail       (skip was lifted but the package fails)
//   fail    →  pass       (unintended improvement — usually a flaky package)
//   {pass,skipped,fail} →  not-run   (package missing from the live run)
//
// Plus the inverse: any package present in the live run that is missing from
// the ledger is reported as a new package.
//
// Use --check-allow-new to permit new packages (e.g. after `go run
// ./tools/tcl2go` regenerates a new test file). The default behavior is
// strict: any drift is a failure.

package main

import (
	"fmt"
	"os"
	"path/filepath"
)

// checkResult is the structured summary of a --check diff. It is exported via
// --check-format json so a future pre-commit hook can parse it.
type checkResult struct {
	BaselineStamp string         `json:"baseline_run_stamp"`
	LiveStamp     string         `json:"live_run_stamp"`
	Total         int            `json:"total"`
	Unexpected    []checkFlip    `json:"unexpected_flips"`
	Missing       []checkMissing `json:"missing_from_ledger"`
	Unattributed  []string       `json:"unattributed_drift"`
	Stats         map[string]int `json:"stats"`
}

// checkFlip records one package whose live state diverges from the ledger.
type checkFlip struct {
	Package     string `json:"package"`
	LedgerState string `json:"ledger_state"`
	LiveState   string `json:"live_state"`
	Goal        string `json:"goal,omitempty"`
	Evidence    string `json:"evidence"`
}

// checkMissing records a package present in the live run but absent from the
// ledger — typically a new test file generated by `tcl2go` and not yet
// triaged.
type checkMissing struct {
	Package   string `json:"package"`
	LiveState string `json:"live_state"`
}

// runCheck wires --check into the existing tools/status flag set and produces
// a deterministic, human-readable diff report. Exit codes:
//
//	0  no unexpected flips
//	1  unexpected flips present
//	2  ledger missing (refusing to compare against nothing)
//	3  baseline run failed (cannot compute live states)
func runCheck(opts options) error {
	repo, err := findRepoRoot(opts.repo)
	if err != nil {
		return err
	}

	// 1. Load the ledger (refuse to compare against nothing).
	ledgerPath := opts.checkLedger
	if ledgerPath == "" {
		ledgerPath = filepath.Join(repo, "tools", "status", "ledger.json")
	}
	ledger, err := loadLedger(ledgerPath)
	if err != nil {
		return fmt.Errorf("load ledger %s: %w (run `go run ./tools/status ledger` to seed)", ledgerPath, err)
	}

	// 2. Force a live run unless the user explicitly wants to check against
	// the cached last_run.json. We do this by reusing the existing loadStaticInfo
	// machinery: pass skipRun=true when the user passes --check-against-cache,
	// else run a fresh suite.
	runOpts := opts
	if !opts.checkAgainstCache {
		runOpts.skipRun = false
	} else {
		runOpts.skipRun = true
	}
	pkgs, liveStamp, err := loadStaticInfo(repo, runOpts)
	if err != nil {
		return fmt.Errorf("compute live states: %w", err)
	}

	// 3. Diff.
	if opts.checkAllowNew {
		res, err := diffAgainstLedgerAllowNew(pkgs, ledger, liveStamp)
		renderCheck(os.Stdout, res)
		if err != nil {
			return err
		}
		return nil
	}
	res, err := diffAgainstLedger(pkgs, ledger, liveStamp)
	if err != nil {
		// Render the full flip list to stderr so the operator sees WHICH
		// packages flipped (not just the count).
		renderCheck(os.Stderr, res)
		return fmt.Errorf("check: %s", err)
	}
	renderCheck(os.Stdout, res)
	return nil
}

// diffAgainstLedger is the strict-mode diff: any state flip or missing
// package is reported as an error.
func diffAgainstLedger(pkgs []*pkgInfo, ledger *ledgerFile, liveStamp string) (*checkResult, error) {
	res, unexpected, missing := computeDiff(pkgs, ledger, liveStamp)
	if len(unexpected) > 0 {
		return res, fmt.Errorf("%d unexpected flip(s) (baseline %s vs live %s); first: %s (%s→%s)",
			len(unexpected), ledger.BaselineStamp, liveStamp,
			unexpected[0].Package, unexpected[0].LedgerState, unexpected[0].LiveState)
	}
	if len(missing) > 0 {
		return res, fmt.Errorf("%d package(s) missing from ledger (baseline %s vs live %s); first: %s (live=%s)",
			len(missing), ledger.BaselineStamp, liveStamp,
			missing[0].Package, missing[0].LiveState)
	}
	return res, nil
}

// diffAgainstLedgerAllowNew is the lenient variant: missing-from-ledger is
// silently accepted (for tcl2go regen flows where new test files appear).
func diffAgainstLedgerAllowNew(pkgs []*pkgInfo, ledger *ledgerFile, liveStamp string) (*checkResult, error) {
	res, unexpected, _ := computeDiff(pkgs, ledger, liveStamp)
	if len(unexpected) > 0 {
		return res, fmt.Errorf("%d unexpected flip(s) (baseline %s vs live %s); first: %s (%s→%s)",
			len(unexpected), ledger.BaselineStamp, liveStamp,
			unexpected[0].Package, unexpected[0].LedgerState, unexpected[0].LiveState)
	}
	return res, nil
}

// computeDiff is the shared diff kernel: it walks the live package list and
// compares each entry to the ledger, returning the checkResult and the two
// filtered lists the strict/lenient callers act on.
func computeDiff(pkgs []*pkgInfo, ledger *ledgerFile, liveStamp string) (*checkResult, []checkFlip, []checkMissing) {
	res := &checkResult{
		BaselineStamp: ledger.BaselineStamp,
		LiveStamp:     liveStamp,
		Stats:         map[string]int{},
	}
	var unexpected []checkFlip
	var missing []checkMissing
	for _, p := range pkgs {
		if p.state == stateNotRun {
			continue
		}
		expected, ok := ledger.Packages[p.name]
		if !ok {
			missing = append(missing, checkMissing{Package: p.name, LiveState: p.state})
			res.Stats["missing_from_ledger"]++
			continue
		}
		// Skip the timeout-suspect placeholder entries — they are not a
		// committed expected state; they only flag work for the operator.
		if expected.State == stateTimeoutSuspect {
			res.Stats["timeout_suspect"]++
			continue
		}
		if expected.State != p.state {
			unexpected = append(unexpected, checkFlip{
				Package:     p.name,
				LedgerState: expected.State,
				LiveState:   p.state,
				Goal:        expected.Goal,
				Evidence:    expected.Evidence,
			})
			res.Stats["flip:"+expected.State+"→"+p.state]++
		}
	}
	res.Total = len(pkgs)
	return res, unexpected, missing
}

// loadLedger reads tools/status/ledger.json. A missing file is a hard error
// — `--check` is meaningless without a baseline.
func loadLedger(path string) (*ledgerFile, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var l ledgerFile
	if err := jsonDecode(b, &l); err != nil {
		return nil, fmt.Errorf("parse %s: %w", path, err)
	}
	return &l, nil
}

// renderCheck prints the diff to w. When there are no flips and w is stdout,
// the output is brief ("PASS"); on stderr or with flips present, the full
// detail is shown.
func renderCheck(w *os.File, r *checkResult) {
	pass := len(r.Unexpected) == 0 && len(r.Missing) == 0
	if pass && w == os.Stdout {
		fmt.Fprintln(w, "check: PASS (no unexpected flips)")
		fmt.Fprintf(w, "  baseline: %s\n", r.BaselineStamp)
		fmt.Fprintf(w, "  live:     %s\n", r.LiveStamp)
		fmt.Fprintf(w, "  total:    %d packages\n", r.Total)
		for k, v := range r.Stats {
			fmt.Fprintf(w, "  %s: %d\n", k, v)
		}
		return
	}
	renderFail(w, r)
}

// renderFail prints the verbose flip-by-flip rendering.
func renderFail(w *os.File, r *checkResult) {
	fmt.Fprintf(w, "check: %d unexpected flip(s), %d missing\n", len(r.Unexpected), len(r.Missing))
	if len(r.Unexpected) > 0 {
		fmt.Fprintln(w, "  unexpected flips:")
		for _, f := range r.Unexpected {
			goal := f.Goal
			if goal == "" {
				goal = "OTHER"
			}
			fmt.Fprintf(w, "    %s: %s → %s (goal=%s)\n",
				f.Package, f.LedgerState, f.LiveState, goal)
		}
	}
	if len(r.Missing) > 0 {
		fmt.Fprintln(w, "  missing from ledger:")
		for _, m := range r.Missing {
			fmt.Fprintf(w, "    %s (live=%s)\n", m.Package, m.LiveState)
		}
	}
}
