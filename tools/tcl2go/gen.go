func groupName(base string) string {
	name := base
	for len(name) > 0 && name[len(name)-1] >= '0' && name[len(name)-1] <= '9' {
		name = name[:len(name)-1]
	}
	if name == base {
		for len(name) > 0 && name[len(name)-1] >= 'a' && name[len(name)-1] <= 'z' {
			name = name[:len(name)-1]
		}
	}
	if name == "" || len(name) <= 1 || isGoKeyword(name) {
		return base
	}
	return name
}

