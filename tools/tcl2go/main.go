// Command tcl2go converts SQLite TCL test files (.test) into Go test files.
// Usage:
//   go run ./tools/tcl2go/
//   go test ./testgen/... -count=1
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/pijalu/frigolite/tools/tclconvert/tcl"
)

func main() {
	testDir := flag.String("testdir", "ori/sqlite/test", "TCL test directory")
	outDir := flag.String("outdir", "testgen", "output directory for generated tests")
	flag.Parse()

	files, err := filepath.Glob(filepath.Join(*testDir, "*.test"))
	if err != nil {
		fmt.Fprintf(os.Stderr, "glob error: %v\n", err)
		os.Exit(1)
	}

	// If specific files are given on the command line, only process those
	if flag.NArg() > 0 {
		var selected []string
		for _, name := range flag.Args() {
			if !strings.HasSuffix(name, ".test") {
				name += ".test"
			}
			selected = append(selected, filepath.Join(*testDir, name))
		}
		files = selected
	}

	type genFile struct {
		filename string
		content  []byte
	}
	groupFiles := make(map[string][]genFile)

	skipFiles := map[string]bool{
		"all": true, "tester": true, "shared": true, "qtp": true,
	}
	var errors []string
	processed := 0

	for _, testFile := range files {
		base := strings.TrimSuffix(filepath.Base(testFile), ".test")
		if skipFiles[base] {
			continue
		}

		src, err := os.ReadFile(testFile)
		if err != nil {
			errors = append(errors, fmt.Sprintf("read %s: %v", base, err))
			continue
		}

		// Execute TCL through interpreter
		interp := tcl.NewInterp()
		interpErr := interp.Execute(string(src))
		stmts := interp.Stmts()
		if interpErr != nil {
			errors = append(errors, fmt.Sprintf("%s: %v", base, interpErr))
			continue
		}
		if len(stmts) == 0 {
			continue
		}

		// Generate Go test file
		filename, content := generateTestFile(base, stmts)
		pkg := groupName(base)
		groupFiles[pkg] = append(groupFiles[pkg], genFile{filename, content})
		processed++
	}

	// Write generated files
	var generated int
	for pkg, files := range groupFiles {
		// Create package directory
		pkgDir := filepath.Join(*outDir, pkg)
		os.MkdirAll(pkgDir, 0755)

		for _, gf := range files {
			// Determine output path from filename (which is like "testgen/with/with1_test.go")
			// The filename is relative to testgen, so just take the basename
			outPath := filepath.Join(pkgDir, filepath.Base(gf.filename))
			if err := os.WriteFile(outPath, gf.content, 0644); err != nil {
				fmt.Fprintf(os.Stderr, "write %s: %v\n", outPath, err)
				continue
			}
			generated++
		}
	}

	// Generate utility package
	genUtil(filepath.Join(*outDir, "util"))

	fmt.Printf("Generated %d test files across %d packages\n", generated, len(groupFiles))
	if len(errors) > 0 {
		fmt.Printf("Errors (%d):\n", len(errors))
		for _, e := range errors {
			fmt.Printf("  %s\n", e)
		}
	}
}

// genUtil generates the shared utility package with the flatten function.
func genUtil(dir string) {
	os.MkdirAll(dir, 0755)
	utilContent := `// Code generated by tcl2go; DO NOT EDIT.
package util

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/pijalu/frigolite"
)

// Flatten converts a query result to a space-separated string.
func Flatten(res *frigolite.Result) string {
	var parts []string
	for _, row := range res.Rows {
		for _, val := range row {
			if val == nil {
				parts = append(parts, "NULL")
			} else {
				parts = append(parts, formatValue(val))
			}
		}
	}
	return strings.Join(parts, " ")
}

func formatValue(v interface{}) string {
	switch x := v.(type) {
	case int64:
		return strconv.FormatInt(x, 10)
	case float64:
		return strconv.FormatFloat(x, 'g', -1, 64)
	case string:
		return x
	case []byte:
		return string(x)
	default:
		return fmt.Sprintf("%v", x)
	}
}
`
	os.WriteFile(filepath.Join(dir, "util.go"), []byte(utilContent), 0644)
}